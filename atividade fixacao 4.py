# Laço de repetição para solicitar 5 produtos
for pdoduto in range(1, 6):
    nome_produto = input(f"Digite o nome do produto {pdoduto}: ")
    print(f"-> Produto '{nome_produto}' cadastrado com sucesso!\n")

# Mensagem final informando a conclusão
print("Todos os 5 produtos foram cadastrados com sucesso!")


